import { dateTime } from "../format";
import type { AnalysisDetail, ContentCredentials } from "../types";

/**
 * Content Credentials (C2PA): what the file's signer declared about how it was
 * made, and whether that declaration can be relied on.
 *
 * A declaration is the signer's claim, not a finding. It is only as strong as
 * the signature: TRUSTED (signer on the C2PA Trust List, file unchanged) is
 * worth a lot; VALID (file unchanged, signer unknown) is worth little, because
 * anyone can make a certificate; INVALID means the claims no longer describe
 * this file at all.
 */

/** IPTC digital source types, as a person would say them. */
const SOURCE_TYPE: Record<string, string> = {
  digitalCapture: "captured by a camera",
  computationalCapture: "captured by a camera with computational processing",
  negativeFilm: "scanned from a film negative",
  positiveFilm: "scanned from film",
  print: "scanned from a print",
  trainedAlgorithmicMedia: "generated by AI",
  compositeWithTrainedAlgorithmicMedia: "combined with AI-generated content",
  algorithmicallyEnhanced: "enhanced by an algorithm",
  compositeSynthetic: "combined with synthetic content",
  algorithmicMedia: "generated by an algorithm (not AI)",
  digitalArt: "made by a person with software",
  virtualRecording: "recorded in a virtual environment",
  screenCapture: "a screenshot",
  composite: "combined from several sources",
  compositeCapture: "combined from several camera captures",
  minorHumanEdits: "lightly edited by a person",
  dataDrivenMedia: "generated from data",
};

const AI_TYPES = new Set(["trainedAlgorithmicMedia", "compositeWithTrainedAlgorithmicMedia", "algorithmicallyEnhanced"]);

const ACTION: Record<string, string> = {
  "c2pa.created": "Created",
  "c2pa.opened": "Opened",
  "c2pa.edited": "Edited",
  "c2pa.edited.metadata": "Metadata edited",
  "c2pa.placed": "Content added",
  "c2pa.removed": "Content removed",
  "c2pa.cropped": "Cropped",
  "c2pa.resized": "Resized",
  "c2pa.color_adjustments": "Colours adjusted",
  "c2pa.filtered": "Filtered",
  "c2pa.drawing": "Drawn on",
  "c2pa.converted": "Converted",
  "c2pa.transcoded": "Re-encoded",
  "c2pa.repackaged": "Repackaged",
  "c2pa.published": "Published",
  "c2pa.watermarked": "Watermarked",
};

const actionLabel = (a: string | null) =>
  a ? ACTION[a] ?? a.replace(/^c2pa\./, "").replace(/[._]/g, " ").replace(/^./, (c) => c.toUpperCase()) : "Unnamed step";

export const sourceTypeLabel = (t: string) => SOURCE_TYPE[t] ?? t.replace(/([a-z])([A-Z])/g, "$1 $2").toLowerCase();

/** The list a signer was checked against, as a phrase. */
function trustListName(c: ContentCredentials | null | undefined): string {
  if (!c?.trust_list?.loaded) return "a trust list";
  return c.trust_list.name === "C2PA-TRUST-LIST" ? "the official C2PA Trust List" : "this server's trust list";
}

/** The status as a pill and one plain sentence. */
export function credentialsSummary(c: ContentCredentials | null | undefined): { label: string; tone: string; lead: string } {
  const who = c?.signer?.common_name ?? "an unnamed signer";
  switch (c?.status) {
    case "TRUSTED":
      return { label: "Signed · trusted signer", tone: "ok",
        lead: `Signed by ${who}, a signer on ${trustListName(c)}, and the file has not changed since. What the signer declared below can be relied on as their statement.` };
    case "VALID":
      return { label: "Signed · signer not verified", tone: "warn",
        lead: c?.trust_list && !c.trust_list.loaded
          ? `Signed by ${who} and unchanged since. No trust list is installed on this server, so whether the signer is genuine was not checked; treat the claims below as unverified.`
          : `Signed by ${who} and unchanged since, but the signer is not on ${trustListName(c)}. Anyone can make such a certificate, so treat the claims below as unverified.` };
    case "INVALID":
      return { label: "Altered after signing", tone: "neg",
        lead: "The file carries Content Credentials, but it was changed after signing or the record is damaged. The claims below no longer describe this file." };
    case "NO_MANIFEST":
      return { label: "None in this file", tone: "hollow",
        lead: "This file carries no Content Credentials. Most photos and many AI images have none, and websites often strip them, so this says nothing either way." };
    case "FAILED":
      return { label: "Could not be read", tone: "hollow", lead: "The Content Credentials in this file could not be read." };
    case "UNAVAILABLE":
      return { label: "Not checked", tone: "hollow", lead: "Content Credentials are not checked on this server." };
    default:
      return { label: "Not checked", tone: "hollow", lead: "Content Credentials were not checked for this analysis." };
  }
}

/** What an intact manifest declares about the content's origin, or null. */
export function declaredOrigin(c: ContentCredentials | null | undefined): { ai: boolean; text: string } | null {
  if (!c || (c.status !== "TRUSTED" && c.status !== "VALID")) return null;
  const types = c.digital_source_types ?? [];
  if (types.length === 0) return null;
  return { ai: types.some((t) => AI_TYPES.has(t)), text: types.map(sourceTypeLabel).join("; ") };
}

/** For the AI-generation card: the signer's own declaration, beside the detector. */
export function DeclaredOrigin({ c }: { c: ContentCredentials | null | undefined }) {
  const origin = declaredOrigin(c);
  if (!c || !origin) return null;
  const trusted = c.status === "TRUSTED";
  return (
    <div className={"declared " + (origin.ai ? "ai" : "") + (trusted ? " trusted" : "")} role="note">
      <p className="declared-head">
        <span className={"pill " + (origin.ai ? "warn" : "")}>Content Credentials</span>
        <span>{origin.ai ? "Declared AI-generated" : "Declared origin"}</span>
      </p>
      <p className="sub">
        {c.signer?.common_name ?? "The signer"} declares this file {origin.text}.{" "}
        {trusted
          ? `The signer is on ${trustListName(c)} and the file is unchanged since signing.`
          : "The signer could not be verified, so this is an unverified claim."}
        {" "}This is the signer's statement, reported beside the detector score, not combined with it.
      </p>
    </div>
  );
}

function TrustNote({ c }: { c: ContentCredentials }) {
  if (!c.trust_list) return null;
  return (
    <p className="sub creds-trust">
      {c.trust_list.loaded
        ? `Signers checked against ${trustListName(c)} (${c.trust_list.anchors ?? "?"} root certificates).`
        : "No trust list is installed on this server, so no signer can be confirmed as trusted."}
      {c.sdk_version ? ` C2PA SDK ${c.sdk_version}.` : ""}
    </p>
  );
}

export function ContentCredentialsCard({ d }: { d: AnalysisDetail }) {
  const c = d.content_credentials;
  const s = credentialsSummary(c);
  const hasManifest = c && ["TRUSTED", "VALID", "INVALID"].includes(c.status);
  const failures = (c?.failures ?? []).filter((f) => f.code !== "signingCredential.untrusted");
  const origin = declaredOrigin(c);

  return (
    <section className="card creds" aria-labelledby="creds-h">
      <div className="card-head">
        <h2 id="creds-h">Content Credentials</h2>
        <span className={"pill " + s.tone} title={c?.status === "UNAVAILABLE" && c.reason ? c.reason : undefined}>{s.label}</span>
      </div>
      <p className="branch-rationale">{s.lead}</p>

      {origin && (
        <p className={"creds-origin" + (origin.ai ? " ai" : "")}>
          Declared: this file was <strong>{origin.text}</strong>.
        </p>
      )}

      {hasManifest && c && (
        <dl className="branch-facts creds-facts">
          <div><dt>Signed by</dt><dd>{c.signer?.common_name ?? "—"}</dd></div>
          <div><dt>Certificate issuer</dt><dd>{c.signer?.issuer ?? "—"}</dd></div>
          <div><dt>Signed at</dt><dd className="num">{c.signer?.signed_at ? dateTime(c.signer.signed_at) : "not stated"}</dd></div>
          <div><dt>Made with</dt><dd>{c.claim_generator ?? "not stated"}</dd></div>
          {!!c.ingredients && <div><dt>Built from</dt><dd className="num">{c.ingredients} earlier file{c.ingredients === 1 ? "" : "s"}</dd></div>}
        </dl>
      )}

      {hasManifest && (c?.actions?.length ?? 0) > 0 && (
        <>
          <h4 className="branch-sub">History declared by the signer</h4>
          <ol className="creds-actions">
            {c!.actions!.map((a, i) => (
              <li key={i}>
                <span className="creds-action">{actionLabel(a.action)}</span>
                {a.digital_source_type && (
                  <span className={"sub-inline" + (AI_TYPES.has(a.digital_source_type) ? " ai" : "")}>
                    {sourceTypeLabel(a.digital_source_type)}
                  </span>
                )}
                {a.software_agent && <span className="sub-inline">with {a.software_agent}</span>}
                {a.when && <span className="sub-inline num">{dateTime(a.when)}</span>}
              </li>
            ))}
          </ol>
        </>
      )}

      {c?.status === "INVALID" && failures.length > 0 && (
        <div className="branch-limits">
          <h4>Why validation failed</h4>
          <ul>{failures.map((f, i) => <li key={i}>{f.explanation ?? f.code}</li>)}</ul>
        </div>
      )}

      {c && <TrustNote c={c} />}
    </section>
  );
}
