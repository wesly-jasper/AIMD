"""
No route serves evidence, analysis or reports to an unauthenticated caller.

This file carries ``real_auth``, so the conftest identity override does not
apply: these requests go through the genuine dependency. That matters, because
every *other* integration test runs with auth overridden and therefore cannot
notice if a router loses its ``dependencies=authenticated``.

The route table is walked rather than listed by hand. A new endpoint is
protected by default -- authentication is applied per router in ``app.main`` --
and if someone mounts a router without it, this test names the path.

The state being guarded against is the one that actually existed: the auth
dependency was wired to a single route (``/auth/me``) and returned
``anonymous_analyst`` when no token was presented, so upload, download, analysis
and all four report formats answered requests with no credentials.
"""
import pytest
from fastapi.routing import APIRoute
from fastapi.testclient import TestClient

from app.main import app

pytestmark = pytest.mark.real_auth

client = TestClient(app)

#: Paths that must stay reachable without credentials, each with the reason.
#: Anything not listed here is required to refuse an anonymous caller.
PUBLIC_PATHS: dict[str, str] = {
    "/health": "liveness probe; reports no evidence and no case data",
    "/api/v1/health": "same probe under the versioned prefix",
    "/api/v1/auth/login": "obtaining a token cannot itself require one",
    "/api/v1/auth/signup": "creating an account cannot require one",
    # Generated by FastAPI, not by this codebase.
    "/openapi.json": "API schema",
    "/docs": "API schema UI",
    "/docs/oauth2-redirect": "API schema UI",
    "/redoc": "API schema UI",
}


def _protected_routes() -> list[tuple[str, str]]:
    found: list[tuple[str, str]] = []
    for route in app.routes:
        if not isinstance(route, APIRoute):
            continue
        if route.path in PUBLIC_PATHS:
            continue
        if route.path.startswith("/__test__/"):
            continue
        for method in sorted(route.methods or []):
            if method in {"HEAD", "OPTIONS"}:
                continue
            found.append((method, route.path))
    return found


def _concrete(path: str) -> str:
    """Fill path parameters. The value never matters: 401 precedes lookup."""
    out = []
    for segment in path.split("/"):
        out.append("never-resolved" if segment.startswith("{") else segment)
    return "/".join(out)


def test_the_route_table_is_not_empty():
    """A guard that walks nothing would pass silently."""
    routes = _protected_routes()
    assert len(routes) >= 12, f"only found {len(routes)} protected routes: {routes}"


@pytest.mark.parametrize("method,path", _protected_routes())
def test_route_refuses_an_anonymous_caller(method: str, path: str):
    response = client.request(method, _concrete(path), json={})

    assert response.status_code == 401, (
        f"{method} {path} answered an unauthenticated request with "
        f"{response.status_code}. Every router must be mounted with "
        f"dependencies=authenticated in app.main."
    )
    # 401 must be reached before the handler runs, so nothing about the
    # requested resource is disclosed -- not even whether it exists.
    assert "never-resolved" not in response.text


@pytest.mark.parametrize("method,path", _protected_routes())
def test_route_refuses_a_forged_token(method: str, path: str):
    """A token signed with a key the server does not hold is not a credential."""
    from jose import jwt

    forged = jwt.encode(
        {"sub": "case_admin", "role": "admin"},
        "a-key-the-server-does-not-have-padding",
        algorithm="HS256",
    )
    response = client.request(
        method,
        _concrete(path),
        json={},
        headers={"Authorization": f"Bearer {forged}"},
    )
    assert response.status_code == 401, f"{method} {path} accepted a forged token"


def test_health_stays_public_and_discloses_no_case_data():
    response = client.get("/health")
    assert response.status_code == 200

    body = response.text.lower()
    # A liveness probe is the one unauthenticated surface, so it must not become
    # a window onto the evidence store.
    for leak in ("media_id", "analysis_id", "filename", "sha256", "username"):
        assert leak not in body, f"/health disclosed {leak!r} to an anonymous caller"


def test_login_stays_public():
    """It answers 401 for bad credentials, not for a missing token."""
    response = client.post(
        "/api/v1/auth/login",
        json={"username": "nobody", "password": "nothing-correct-here"},
    )
    assert response.status_code == 401
    assert response.json()["error"]["message"] == "Incorrect email or password"


def test_every_public_path_is_a_deliberate_exemption():
    """
    The exemption list is checked against reality so it cannot rot: a path listed
    here that no longer exists would silently excuse a future route of the same
    name from authentication.
    """
    real_paths = {getattr(r, "path", "") for r in app.routes}
    stale = set(PUBLIC_PATHS) - real_paths
    assert not stale, f"PUBLIC_PATHS exempts paths that do not exist: {sorted(stale)}"
