"""Build the AI-generation benchmark: independent Commons images, transformed copies, frozen holdout.

The first evaluation set had 15 GPT-image and 7 Grok/Flux files, no transformed
copies, and a test split that every decision since was checked against. This
builds a second set to fix all three:

  crawl      list candidate files per generator from Commons categories (and
             their subcategories), and real photographs from Quality images
             sampled across the category, never only its first titles.
  fetch      download 960 px renditions, at most --per-uploader per uploader
             and generator, so one prolific account cannot dominate a result;
             anything already in an existing manifest is skipped.
  transform  write re-encoded copies of every file (tags: jpeg_q70, resize_50,
             crop_80, webp_q75, social); a copy shares its original's group, so
             it is always in the same split.
  split      assign val / holdout by uploader. The holdout is then frozen with
             ``scripts/evaluate.py freeze``; nothing may be fitted on it.

Usage (from backend/, with the venv python; needs WIKIMEDIA_CONTACT):

    python scripts/build_benchmark.py crawl
    python scripts/build_benchmark.py fetch
    python scripts/build_benchmark.py transform
    python scripts/build_benchmark.py split
    python scripts/evaluate.py freeze <out>/manifest.split.json

Every file keeps its Commons page, uploader and licence in the manifest.
"""
