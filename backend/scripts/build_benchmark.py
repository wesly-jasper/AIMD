DEFAULT_OUT = Path(os.environ.get("LOCALAPPDATA", BACKEND)) / "Temp" / "aimd-reliability" / "sets" / "bench2"

#: Category roots per generator. Subcategories are followed (``--depth``).
GENERATORS: dict[str, list[str]] = {
    "GPT-image": [
        "GPT Image", "Images generated by GPT Image 1", "Images generated by GPT Image 1.5",
        "Images generated by GPT Image 2", "Images generated by GPT Image 2.5",
        "Images generated by GPT-4o", "Images generated by ChatGPT",
    ],
    "Grok": ["Images generated by Grok"],
    "Flux": ["Flux (text-to-image model)", "Images generated by Flux"],
    "Imagen / Gemini": ["Images generated by Imagen", "Images generated by Gemini"],
    "Ideogram": ["Images generated by Ideogram"],
    "Midjourney": ["Images generated by Midjourney"],
    "Stable Diffusion": ["Images generated by Stable Diffusion"],
    "DALL-E": ["Images generated by DALL-E", "DALL-E 3", "DALL-E 2"],
}
#: Full-text searches for generators that Commons categories barely cover.
#: A hit counts only when its *title* names the generator (``TITLE_MATCH``):
#: "flux" alone also finds papers on heat flux.
SEARCHES: dict[str, list[str]] = {
    "Flux": ['intitle:FLUX', '"FLUX.1"', '"Flux 1.1"', '"FLUX.2"', '"Flux Kontext"', '"Black Forest Labs"'],
    "Grok": ['intitle:Grok', '"Grok Aurora"', '"Grok Imagine"', '"generated by Grok"', '"made with Grok"'],
    "GPT-image": ['"GPT Image"', '"gpt-image-1"', '"generated by ChatGPT"', '"made with ChatGPT"',
                  'intitle:ChatGPT', '"GPT-4o image"'],
}
TITLE_MATCH = {
    "Flux": re.compile(r"\bflux[ ._-]?(1|2|pro|dev|schnell|kontext)|\(flux\b|black forest labs", re.IGNORECASE),
    "Grok": re.compile(r"\bgrok\b", re.IGNORECASE),
    "GPT-image": re.compile(r"chat ?gpt|gpt[ -]?(image|4o)", re.IGNORECASE),
}
REAL_CATEGORY = "Quality images"

#: Categories and titles that are not a generator's output as such: edits of
#: real photos, screenshots, logos, side-by-side comparisons.
_EXCLUDE = re.compile(
    r"retouch|edited|screenshot|logo|tweet|scandal|comparison|\bvs\.?\b|collage|composite|"
    r"meme|diagram|chart|map of|icon|banner|before and after",
    re.IGNORECASE,
)
_MIMES = {"image/jpeg": ".jpg", "image/png": ".png", "image/webp": ".webp"}
THUMB_WIDTH = 960
MIN_SIDE = 256


def _client(args) -> CommonsClient:
    contact = args.contact or settings.wikimedia_contact
    if not contact:
        sys.exit("--contact (or WIKIMEDIA_CONTACT) is required by Wikimedia's User-Agent policy")
    return CommonsClient(contact, min_interval=1.0)


def _existing_sources(paths: list[Path]) -> set[str]:
    """Commons titles already used by another evaluation set."""
    seen: set[str] = set()
    for path in paths:
        for item in load_manifest(path):
            source = str(item.extra.get("source") or "")
            if "/wiki/File:" in source:
                seen.add(source.split("/wiki/", 1)[1].replace("_", " "))
    return seen


def _existing_uploaders(paths: list[Path]) -> set[str]:
    """Uploaders in another evaluation set. None of their files may be used here:
    one person's images share a prompt style and pipeline, so they would put the
    same source on both sides of a split -- the frozen holdout included."""
    seen: set[str] = set()
    for path in paths:
        for item in load_manifest(path):
            uploader = item.extra.get("uploader")
            if uploader:
                seen.add(str(uploader))
    return seen


def _usable(f) -> bool:
    if f.mime not in _MIMES or _EXCLUDE.search(f.title):
        return False
    return (f.width or 0) >= MIN_SIDE and (f.height or 0) >= MIN_SIDE


def _record(f, generator: str | None, category: str) -> dict:
    return {
        "title": f.title, "page_url": f.page_url, "download_url": f.download_url,
        "uploader": f.uploader, "sha1": f.sha1, "mime": f.mime,
        "licence": f.licence, "artist": f.artist, "category": category,
        "generator": generator,
    }


# ── crawl ─────────────────────────────────────────────────────────────────────

def cmd_crawl(args) -> int:
    out: Path = args.out
    out.mkdir(parents=True, exist_ok=True)
    candidates: list[dict] = []
    with _client(args) as client:
        for generator, roots in GENERATORS.items():
            queue = [(root, 0) for root in roots]
            visited: set[str] = set()
            found = 0
            while queue:
                category, depth = queue.pop(0)
                if category in visited or (depth and _EXCLUDE.search(category)):
                    continue
                visited.add(category)
                try:
                    for f in client.category_files(category, thumb_width=THUMB_WIDTH):
                        if _usable(f):
                            candidates.append(_record(f, generator, category))
                            found += 1
                    if depth < args.depth:
                        queue.extend((sub, depth + 1) for sub in client.subcategories(category))
                except CommonsError as exc:
                    print(f"  {category}: {exc}")
            for query in SEARCHES.get(generator, []):
                try:
                    for f in client.search_files(query, thumb_width=THUMB_WIDTH):
                        if _usable(f) and TITLE_MATCH[generator].search(f.title):
                            candidates.append(_record(f, generator, f"search: {query}"))
                            found += 1
                except CommonsError as exc:
                    print(f"  search {query!r}: {exc}")
            print(f"{generator}: {found} candidates from {len(visited)} categories"
                  f"{' and title search' if generator in SEARCHES else ''}", flush=True)

        rng = random.Random(args.seed)
        prefixes = sorted({rng.choice("ABCDEFGHIJKLMNOPRSTUVW") + rng.choice("aeiou")
                           for _ in range(args.real_prefixes)})
        reals = 0
        for prefix in prefixes:
            taken = 0
            try:
                for f in client.category_files(REAL_CATEGORY, thumb_width=THUMB_WIDTH,
                                               start_sortkey_prefix=prefix):
                    if _usable(f) and f.mime == "image/jpeg":  # camera photographs
                        candidates.append(_record(f, None, REAL_CATEGORY))
                        taken += 1
                        reals += 1
                    if taken >= args.real_per_prefix:
                        break
            except CommonsError as exc:
                print(f"  {REAL_CATEGORY} from {prefix!r}: {exc}")
        print(f"real: {reals} candidates from {len(prefixes)} sort-key prefixes")

    # A file in two generators' categories is ambiguous: dropped from both.
    by_title: dict[str, set] = {}
    for c in candidates:
        by_title.setdefault(c["title"], set()).add(c["generator"])
    clean, seen = [], set()
    for c in candidates:
        if len(by_title[c["title"]]) == 1 and c["title"] not in seen:
            seen.add(c["title"])
            clean.append(c)
    (out / "candidates.json").write_text(json.dumps(clean, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"{len(clean)} candidates written to {out / 'candidates.json'}")
    return 0


# ── fetch ─────────────────────────────────────────────────────────────────────

def _slug(text: str) -> str:
    return re.sub(r"[^a-z0-9]+", "", text.lower())[:10] or "x"


def cmd_fetch(args) -> int:
    out: Path = args.out
    candidates = json.loads((out / "candidates.json").read_text(encoding="utf-8"))
    used = _existing_sources(args.exclude)
    banned = _existing_uploaders(args.exclude) if args.exclude_uploaders else set()
    rng = random.Random(args.seed)
    rng.shuffle(candidates)  # so the per-uploader cap does not favour A-titles

    chosen: list[dict] = []
    per_uploader: dict[tuple, int] = {}
    per_generator: dict[str, int] = {}
    sha1s: set[str] = set()
    for c in candidates:
        gen = c["generator"] or "real"
        cap = args.reals if gen == "real" else args.per_generator
        key = (gen, c["uploader"])
        if (c["title"] in used or c["uploader"] in banned or c["sha1"] in sha1s
                or per_generator.get(gen, 0) >= cap
                or per_uploader.get(key, 0) >= (args.real_per_uploader if gen == "real" else args.per_uploader)):
            continue
        sha1s.add(c["sha1"])
        per_uploader[key] = per_uploader.get(key, 0) + 1
        per_generator[gen] = per_generator.get(gen, 0) + 1
        chosen.append(c)

    manifest_path = out / "manifest.json"
    items = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else []
    have = {i["source"] for i in items}
    files = out / "files"
    with _client(args) as client:
        counter: dict[str, int] = {}
        for c in chosen:
            gen = c["generator"] or "real"
            n = counter[gen] = counter.get(gen, 0) + 1
            if c["page_url"] in have:
                continue
            name = f"{_slug(gen)}_{n:03d}{_MIMES[c['mime']]}"
            try:
                sha256, size, _ = client.download(c["download_url"], files / name, max_bytes=30_000_000)
            except CommonsError as exc:
                print(f"skip {c['title']}: {exc}")
                continue
            items.append({
                "id": name, "file": f"files/{name}",
                "label": "real" if gen == "real" else "ai_generated",
                "generator": None if gen == "real" else gen,
                # The uploader is the unit of independence: one person's
                # images share a prompt style, a pipeline and an upload path.
                "group": f"{_slug(gen)}:{c['uploader']}",
                "tags": ["original"], "sha256": sha256,
                "source": c["page_url"], "uploader": c["uploader"],
                "licence": c["licence"], "artist": c["artist"], "category": c["category"],
            })
            manifest_path.write_text(json.dumps(items, indent=1, ensure_ascii=False), encoding="utf-8")
            print(f"{name}  {gen:16}  {size // 1024} KB  {c['title'][:60]}")
    counts: dict[str, int] = {}
    for i in items:
        counts[i["generator"] or "real"] = counts.get(i["generator"] or "real", 0) + 1
    print(json.dumps(counts, indent=1))
    return 0


# ── transform ─────────────────────────────────────────────────────────────────

def _save(img: Image.Image, fmt: str, **kw) -> bytes:
    buf = io.BytesIO()
    img.save(buf, format=fmt, **kw)
    return buf.getvalue()


def _variants(img: Image.Image) -> dict[str, tuple[str, bytes]]:
    """Ordinary things that happen to an image after it leaves its generator."""
    img = img.convert("RGB")
    w, h = img.size
    half = img.resize((max(1, w // 2), max(1, h // 2)), Image.LANCZOS)
    cw, ch = int(w * 0.8), int(h * 0.8)
    left, top = (w - cw) // 2, (h - ch) // 2
    crop = img.crop((left, top, left + cw, top + ch))
    scale = 720 / max(w, h)
    social = img.resize((max(1, round(w * scale)), max(1, round(h * scale))), Image.LANCZOS) if scale < 1 else img
    return {
        "jpeg_q70": (".jpg", _save(img, "JPEG", quality=70)),
        "resize_50": (".jpg", _save(half, "JPEG", quality=90)),
        "crop_80": (".jpg", _save(crop, "JPEG", quality=90)),
        "webp_q75": (".webp", _save(img, "WEBP", quality=75)),
        # A messaging-app style re-share: 720 px long side, JPEG q75, 4:2:0.
        "social": (".jpg", _save(social, "JPEG", quality=75, subsampling=2)),
    }


def cmd_transform(args) -> int:
    out: Path = args.out
    manifest_path = out / "manifest.json"
    items = json.loads(manifest_path.read_text(encoding="utf-8"))
    originals = [i for i in items if i.get("tags") == ["original"]]
    have = {i["id"] for i in items}
    added = 0
    for item in originals:
        stem = Path(item["id"]).stem
        with Image.open(out / item["file"]) as img:
            variants = _variants(img)
        for tag, (ext, data) in variants.items():
            vid = f"{stem}__{tag}{ext}"
            if vid in have:
                continue
            (out / "files" / vid).write_bytes(data)
            items.append({**item, "id": vid, "file": f"files/{vid}", "tags": [tag],
                          "sha256": hashlib.sha256(data).hexdigest(), "derived_from": item["id"]})
            added += 1
    manifest_path.write_text(json.dumps(items, indent=1, ensure_ascii=False), encoding="utf-8")
    print(f"{added} transformed copies of {len(originals)} originals; {len(items)} items")
    return 0


# ── split ─────────────────────────────────────────────────────────────────────

def _phash(path: Path):
    import imagehash

    with Image.open(path) as img:
        return imagehash.phash(img.convert("RGB"))


def cmd_dedupe(args) -> int:
    """
    Near-duplicates are the same picture re-encoded, resized or lightly edited.
    One that matches a file in another set is dropped -- it would let a
    calibration, or this set's results, see a holdout picture again. Within this
    set, near-duplicates are put in one group, so a split never separates them.
    Runs on originals, before ``transform``.
    """
    out: Path = args.out
    manifest_path = out / "manifest.json"
    items = json.loads(manifest_path.read_text(encoding="utf-8"))
    if any(i.get("tags") != ["original"] for i in items):
        print("refused: dedupe runs before transform (the manifest already has transformed copies)")
        return 1
    reference = []
    for path in args.against:
        for item in load_manifest(path):
            if "original" in item.tags or not item.tags:
                try:
                    reference.append((path.parent.name, item.id, _phash(Path(item.path))))
                except OSError:
                    continue
    print(f"reference: {len(reference)} originals from {len(args.against)} manifests")
    kept, dropped, merged = [], [], 0
    hashes = []
    for item in items:
        h = _phash(out / item["file"])
        hit = next((r for r in reference if h - r[2] <= args.max_distance), None)
        if hit:
            dropped.append({"id": item["id"], "near_duplicate_of": f"{hit[0]}/{hit[1]}", "distance": int(h - hit[2])})
            (out / item["file"]).unlink(missing_ok=True)
            continue
        twin = next((k for k, kh in zip(kept, hashes) if h - kh <= args.max_distance), None)
        if twin is not None and twin["group"] != item["group"]:
            item["group"] = twin["group"]
            item["near_duplicate_of"] = twin["id"]
            merged += 1
        item["phash"] = str(h)
        kept.append(item)
        hashes.append(h)
    manifest_path.write_text(json.dumps(kept, indent=1, ensure_ascii=False), encoding="utf-8")
    (out / "dedupe.json").write_text(json.dumps({"dropped": dropped, "merged_into_one_group": merged,
                                                  "max_distance": args.max_distance,
                                                  "against": [str(p) for p in args.against]}, indent=1),
                                     encoding="utf-8")
    print(f"kept {len(kept)}, dropped {len(dropped)} near-duplicates of other sets, "
          f"grouped {merged} near-duplicates within this set")
    for d in dropped[:20]:
        print(f"  dropped {d['id']} ~ {d['near_duplicate_of']} (distance {d['distance']})")
    return 0


def cmd_split(args) -> int:
    out: Path = args.out
    items = load_manifest(out / "manifest.json")
    problems = validate(items)
    if problems:
        print("\n".join(problems[:20]))
        return 1
    if args.no_holdout:
        fractions = {"train": args.train, "val": 1 - args.train}
    else:
        fractions = {"train": args.train, "val": args.val, "holdout": 1 - args.val - args.train}
    assign_splits(items, {k: v for k, v in fractions.items() if v > 0}, seed=args.seed, overwrite=True)
    leaks = split_leakage(items)
    if leaks:
        print("\n".join(leaks[:20]))
        return 1
    write_manifest(items, out / "manifest.split.json")
    counts: dict[tuple, int] = {}
    for i in items:
        if "original" in i.tags:
            key = (i.split, i.generator or "real")
            counts[key] = counts.get(key, 0) + 1
    for (split, gen), n in sorted(counts.items()):
        print(f"{split:8} {gen:18} {n} originals")
    hint = "" if args.no_holdout else " -- freeze it with scripts/evaluate.py freeze"
    print(f"written: {out / 'manifest.split.json'}{hint}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--contact", help="email or URL for the User-Agent (default: WIKIMEDIA_CONTACT)")
    parser.add_argument("--seed", default="aimd-bench2-v1")
    sub = parser.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("crawl")
    p.add_argument("--depth", type=int, default=2)
    p.add_argument("--real-prefixes", type=int, default=40)
    p.add_argument("--real-per-prefix", type=int, default=12)
    p.set_defaults(func=cmd_crawl)

    p = sub.add_parser("fetch")
    p.add_argument("--per-generator", type=int, default=60)
    p.add_argument("--per-uploader", type=int, default=6)
    p.add_argument("--reals", type=int, default=240)
    p.add_argument("--real-per-uploader", type=int, default=3)
    p.add_argument("--exclude", type=Path, nargs="*", default=[],
                   help="existing manifests whose Commons files must not be reused")
    p.add_argument("--exclude-uploaders", action="store_true",
                   help="also skip every uploader that appears in an --exclude manifest")
    p.set_defaults(func=cmd_fetch)

    p = sub.add_parser("dedupe", help="drop near-duplicates of other sets; group near-duplicates within this one")
    p.add_argument("--against", type=Path, nargs="*", default=[],
                   help="manifests (any split, the frozen holdout included) to compare with")
    p.add_argument("--max-distance", type=int, default=8, help="pHash Hamming distance counted as a near-duplicate")
    p.set_defaults(func=cmd_dedupe)

    p = sub.add_parser("transform")
    p.set_defaults(func=cmd_transform)

    p = sub.add_parser("split")
    p.add_argument("--val", type=float, default=0.35)
    p.add_argument("--train", type=float, default=0.0,
                   help="fraction for a train split; the rest after train and val is holdout")
    p.add_argument("--no-holdout", action="store_true",
                   help="train and val only (a set added after the holdout was frozen)")
    p.set_defaults(func=cmd_split)

    args = parser.parse_args(argv)
    return args.func(args)


if __name__ == "__main__":
    sys.exit(main())
